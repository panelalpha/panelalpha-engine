<?php

namespace Tests\Integration\Deploy\Platform;

use App\Lib\Deploy\Platform\DeployPlan;
use App\Lib\Deploy\Platform\HostScript;
use App\Lib\Deploy\Platform\PlatformManifest;
use App\Lib\Deploy\Platform\PlatformStage;
use App\Lib\Deploy\Platform\ProjectContext;
use PHPUnit\Framework\TestCase;

/**
 * The whole host script, byte for byte, for the guards, overrides, plans and app config commands.
 */
class HostScriptRenderTest extends TestCase
{
    private const HEADER = "#!/bin/bash\n"
        . "# Generated by PanelAlpha for the prepare stage — do not edit.\n"
        . "# Source: %s\n"
        . "set -euo pipefail\n"
        . "\n"
        . "pa_step() { printf '[panelalpha] %%s: %%s\\n' \"\$1\" \"\$2\" >&2; }\n"
        . "pa_skip() { printf '[panelalpha] %%s: %%s failed (optional, continuing)\\n' \"\$1\" \"\$2\" >&2; }\n"
        . "\n";

    private string $dir = '';

    protected function setUp(): void
    {
        $this->dir = sys_get_temp_dir() . '/pa-host-script-' . bin2hex(random_bytes(8));
        mkdir($this->dir, 0777, true);
    }

    protected function tearDown(): void
    {
        foreach (glob($this->dir . '/*') ?: [] as $file) {
            @unlink($file);
        }
        @rmdir($this->dir);
    }

    /** @param list<array<string, mixed>> $commands */
    private function manifest(array $commands): PlatformManifest
    {
        return PlatformManifest::fromArray([
            'id' => 'demo',
            'label' => 'Demo',
            'priority' => 1,
            'runtime' => 'command',
            'detect' => ['file' => 'demo.json'],
            'commands' => $commands,
        ], 'demo.yaml');
    }

    private function context(): ProjectContext
    {
        $files = [];
        foreach (scandir($this->dir) ?: [] as $entry) {
            if ($entry !== '.' && $entry !== '..') {
                $files[strtolower($entry)] = true;
            }
        }

        return ProjectContext::make($this->dir, $files);
    }

    private function header(string $source): string
    {
        return sprintf(self::HEADER, $source);
    }

    public function test_guards_overrides_and_borrowed_hooks_render_in_order(): void
    {
        $script = HostScript::render(
            $this->manifest([
                [
                    'id' => 'a',
                    'stage' => 'prepare',
                    'run' => 'echo a',
                    'workdir' => 'sub',
                    'timeout' => 30,
                    'optional' => true,
                    'description' => "first\nsecond",
                ],
                ['id' => 'b', 'stage' => 'prepare', 'run' => 'echo b'],
            ]),
            PlatformStage::PREPARE,
            null,
            ['b' => 'echo B'],
            ['hook' => "echo hook\n", 7 => 'echo seven']
        );

        $this->assertSame(
            $this->header('demo.yaml')
            . "# first\n# second\n"
            . "pa_step prepare 'a'\n"
            . "timeout --foreground 30 bash -c '( cd sub && echo a )' || pa_skip prepare 'a'\n"
            . "\n"
            . "pa_step prepare 'b'\n"
            . "echo B\n"
            . "\n"
            . "pa_step prepare 'hook'\n(\nset +u +o pipefail\necho hook\n)\n\n"
            . "pa_step prepare '7'\n(\nset +u +o pipefail\necho seven\n)\n\n",
            $script
        );
    }

    public function test_a_plan_that_names_the_stage_replaces_it_and_drops_the_hooks(): void
    {
        $plan = DeployPlan::fromArray(['prepare' => [['id' => 'x', 'run' => "echo 'x'"]]]);

        $script = HostScript::render(
            $this->manifest([['id' => 'a', 'stage' => 'prepare', 'run' => 'echo a']]),
            PlatformStage::PREPARE,
            null,
            [],
            ['hook' => 'echo hook'],
            [],
            $plan
        );

        $this->assertSame(
            $this->header('demo.yaml')
            . "pa_step prepare 'replaced by the deploy request'\n"
            . "\n"
            . "pa_step prepare 'x'\n"
            . "echo 'x'\n"
            . "\n",
            $script
        );
    }

    public function test_when_guards_filter_manifest_and_app_config_commands_against_the_context(): void
    {
        touch($this->dir . '/yes.txt');
        $appConfig = $this->manifest([
            ['id' => 'own-yes', 'stage' => 'prepare', 'run' => 'echo own-yes', 'when' => ['file' => 'yes.txt']],
            ['id' => 'own-no', 'stage' => 'prepare', 'run' => 'echo own-no', 'when' => ['file' => 'no.txt']],
        ])->stage(PlatformStage::PREPARE);

        $script = HostScript::render(
            $this->manifest([
                ['id' => 'm-yes', 'stage' => 'prepare', 'run' => 'echo m-yes', 'when' => ['file' => 'yes.txt']],
                ['id' => 'm-no', 'stage' => 'prepare', 'run' => 'echo m-no', 'when' => ['file' => 'no.txt']],
            ]),
            PlatformStage::PREPARE,
            $this->context(),
            [],
            [],
            $appConfig
        );

        $this->assertSame(
            $this->header('demo.yaml')
            . "pa_step prepare 'm-yes'\necho m-yes\n\n"
            . "pa_step prepare 'own-yes'\necho own-yes\n\n",
            $script
        );
    }

    public function test_without_a_context_app_config_commands_are_kept_unfiltered(): void
    {
        $appConfig = $this->manifest([
            ['id' => 'own', 'stage' => 'prepare', 'run' => 'echo own', 'when' => ['file' => 'no.txt']],
        ])->stage(PlatformStage::PREPARE);

        $script = HostScript::render(null, PlatformStage::PREPARE, null, [], [], $appConfig);

        $this->assertSame(
            $this->header("the project's app config") . "pa_step prepare 'own'\necho own\n\n",
            $script
        );
    }

    public function test_is_empty_counts_plans_hooks_and_app_config_commands(): void
    {
        $plan = DeployPlan::fromArray(['prepare' => []]);
        $command = $this->manifest([['id' => 'a', 'stage' => 'prepare', 'run' => 'echo a']])->stage(PlatformStage::PREPARE);

        $this->assertTrue(HostScript::isEmpty(null, PlatformStage::PREPARE));
        $this->assertFalse(HostScript::isEmpty(null, PlatformStage::PREPARE, null, [], [], $plan));
        $this->assertFalse(HostScript::isEmpty(null, PlatformStage::PREPARE, null, ['hook' => 'echo']));
        $this->assertFalse(HostScript::isEmpty(null, PlatformStage::PREPARE, null, [], $command));
        $this->assertFalse(HostScript::isEmpty($this->manifest([['id' => 'a', 'stage' => 'prepare', 'run' => 'echo a']]), PlatformStage::PREPARE));
        $this->assertTrue(HostScript::isEmpty($this->manifest([['id' => 'a', 'stage' => 'precheck', 'run' => 'echo a']]), PlatformStage::PREPARE));
    }

    public function test_a_container_stage_names_the_entrypoint_class(): void
    {
        $this->expectException(\InvalidArgumentException::class);
        $this->expectExceptionMessage("'start' does not run on the host; see App\\Lib\\Deploy\\Platform\\StageScript");

        HostScript::render(null, PlatformStage::START);
    }
}
